"""
素数（质数）** 是指在大于 1 的自然数中，除了 1 和它本身以外不再有其他因数的数。例如：2、3、5、7、11 都是素数，而 4、6、8、9 则不是。

编写一个程序，要求如下：

1. **用户输入**：通过 `input()` 函数获取起始数字和结束数字。
  
2. **输入合法性检查**：
  
  * 输入必须是正整数（大于 0 的整数）
  * 结束数字必须大于起始数字
  * 如果输入不合法，给出相应提示并要求重新输入
3. **素数判断**：使用循环判断该范围内每个数字是否为素数。
  
4. **输出结果**：打印该范围内的所有素数，并统计素数的个数。
"""

start = int(input("请输入开始数字："))
end = int(input("请输入结束数字："))
if start <= 0 or end <= 0:
    print("错误：输入必须是正整数（大于 0 的整数），请重新输入！")
elif end <= start:
    print("错误：结束数字必须大于起始数字，请重新输入！")
else:
    num = 0 # 记录素数个数
    i = 2 # 标识除数
    while start < end:
        if start == 1:
            start += 1
        elif start == 2:
            print(f'素数:{start}')
            start += 1
            num += 1
        elif start % i == 0: # 非素数跳过
            start += 1
            i = 2
        else:
            i += 1 # 看下一个除数能不能除尽
            if i * i > start:
                print(f'素数:{start}')
                start += 1
                i = 2
                num += 1
    print(f"素数总{num}个") 


